/** Replace every <i data-i="name" data-s="size"> in root with its SVG. */
export function hydrateIcons(root = document) {
  root.querySelectorAll('i[data-i]').forEach((el) => {
    el.outerHTML = icon(el.dataset.i, +el.dataset.s || 18);
  });
}
